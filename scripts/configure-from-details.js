'use strict';

// One-shot automatic configuration from all_details.txt.
//
// Reads the private details file, validates every supported value, applies the
// results to the local runtime (.env pointer only — secrets never leave the
// private file), and generates the single Railway variable payload needed for
// deployment. Nothing secret is ever printed, logged, or written to a tracked
// file.

const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { loadConfig, getConfigReport, parseDetailsText } = require('../server/config');

const ROOT = path.resolve(__dirname, '..');

function argumentValue(argv, name) {
  const index = argv.indexOf(`--${name}`);
  if (index === -1 || index + 1 >= argv.length) return '';
  return argv[index + 1];
}
function hasFlag(argv, name) {
  return argv.includes(`--${name}`);
}

function railwayPayload(detailsText) {
  // A single Railway private variable carries the whole configuration file.
  return `ALL_DETAILS_TEXT=${String(detailsText).trim()}`;
}

function localEnvContent(detailsPath) {
  return [
    '# Generated by scripts/configure-from-details.js. This file points at the',
    '# private details file; the secrets themselves stay inside that file only.',
    `ALL_DETAILS_FILE=${detailsPath}`,
    ''
  ].join('\n');
}

function redactedSummary(report) {
  const monetag = report.monetag || {};
  const payments = report.payments || {};
  return [
    `configuration source : ${report.source}${report.detailsFileLoaded ? '' : ' (not loaded)'}`,
    `format               : ${report.format || 'n/a'}`,
    `Telegram bot token   : ${report.telegramBotToken}`,
    `Telegram admin id    : ${report.adminTelegramId}`,
    `session secret       : ${report.sessionSecret}`,
    `Firebase project id  : ${report.firebaseProjectId}`,
    `Firebase web config  : ${report.firebaseWebConfig}`,
    `Firebase Admin creds : ${report.firebaseAdminCredentials}`,
    `Monetag sdk/zone     : ${monetag.sdkUrl ? 'present' : 'missing'} / ${monetag.zoneId ? 'present' : 'missing'}`,
    `Monetag publisher    : ${monetag.publisherId ? 'present' : 'missing'}`,
    `Monetag postback     : ${monetag.postbackSecret ? 'present' : 'missing'}`,
    `Monetag enabled      : ${monetag.enabled ? 'yes' : 'no (fail-closed until verified)'}`,
    `payments             : ${payments.depositsEnabled ? 'enabled' : 'disabled'} / ${payments.withdrawalsEnabled ? 'enabled' : 'disabled'}`,
    `admin TOTP           : ${report.adminTotp}`
  ];
}

function nextSteps(config, report) {
  const steps = [];
  const missing = report.requiredMissing || [];
  if (missing.length) {
    steps.push('Missing required values (add them to all_details.txt or as Railway variables):');
    for (const item of missing) steps.push(`  - ${item}`);
  }
  for (const warning of report.warnings || []) steps.push(`warning: ${warning}`);
  if (config.firebaseWebConfig && config.firebaseWebConfig.projectId) {
    steps.push(`Firebase Web SDK values for project ${config.firebaseWebConfig.projectId} are public by design; the server exposes only a presence flag, never the values.`);
  }
  if (config.telegramBotToken && config.publicAppUrl) {
    steps.push('Telegram Mini App URL is configured; the menu button can be set with: npm run telegram:menu');
  } else if (config.telegramBotToken) {
    steps.push('After deploying, set PUBLIC_APP_URL to the actual Railway HTTPS URL, then run: npm run telegram:menu');
  }
  return steps;
}

function run(configureOptions = {}) {
  const argv = configureOptions.argv || process.argv.slice(2);
  const detailsPath = path.resolve(ROOT, argumentValue(argv, 'details') || 'all_details.txt');
  const applyLocal = hasFlag(argv, 'apply-local');
  const applyRailway = hasFlag(argv, 'apply-railway');
  const railwayService = argumentValue(argv, 'railway-service');

  let text;
  try {
    text = fs.readFileSync(detailsPath, 'utf8');
  } catch {
    process.stderr.write('[mag-ia] configure failed: all_details.txt not found. Place it at the project root or pass --details <path>.\n');
    process.exitCode = 1;
    return;
  }

  let parsed;
  try {
    parsed = parseDetailsText(text, 'ALL_DETAILS');
  } catch (error) {
    const code = String(error && error.message || 'PARSE_FAILED').split(':')[0];
    process.stderr.write(`[mag-ia] configure failed (${code}). Fix all_details.txt and rerun.\n`);
    process.exitCode = 1;
    return;
  }

  // Validate through the same loader the server uses, without emitting secrets.
  let config;
  try {
    config = loadConfig({ file: parsed, env: {}, loadDotenv: false, root: ROOT });
  } catch (error) {
    const code = String(error && error.message || 'CONFIG_LOAD_FAILED').split(':')[0];
    process.stderr.write(`[mag-ia] configure failed (${code})\n`);
    process.exitCode = 1;
    return;
  }
  const report = getConfigReport(config);

  process.stdout.write('[mag-ia] configuration report (values redacted)\n');
  for (const line of redactedSummary(report)) process.stdout.write(`  ${line}\n`);
  process.stdout.write('\n[mag-ia] next steps\n');
  for (const step of nextSteps(config, report)) process.stdout.write(`  ${step}\n`);

  if (applyLocal) {
    const envPath = path.join(ROOT, '.env');
    fs.writeFileSync(envPath, localEnvContent(detailsPath), { mode: 0o600 });
    process.stdout.write(`\n[mag-ia] wrote local pointer ${envPath} (ALL_DETAILS_FILE only; no secrets).\n`);
  }

  if (applyRailway) {
    const payload = railwayPayload(text);
    const args = ['variables', 'set', `ALL_DETAILS_TEXT=${payload.slice('ALL_DETAILS_TEXT='.length)}`];
    if (railwayService) args.push('--service', railwayService);
    const result = spawnSync('railway', args, { stdio: 'inherit', cwd: ROOT });
    if (result.error || result.status !== 0) {
      process.stderr.write('[mag-ia] railway CLI failed; run the generated command manually or paste the variable in the Railway dashboard.\n');
      process.exitCode = 1;
      return;
    }
    process.stdout.write('\n[mag-ia] Railway variable ALL_DETAILS_TEXT set for this service.\n');
  } else {
    const preview = railwayPayload(text);
    process.stdout.write('\n[mag-ia] Railway deployment (single private variable, no per-value entry):\n');
    process.stdout.write('  railway variables set "ALL_DETAILS_TEXT=$(cat all_details.txt)"\n');
    process.stdout.write(`  payload length: ${preview.length} chars (value not echoed here)\n`);
    process.stdout.write('  or paste the full contents of all_details.txt as the value of ALL_DETAILS_TEXT in the Railway Variables UI.\n');
  }
}

if (require.main === module) run();

module.exports = { railwayPayload, localEnvContent, redactedSummary, nextSteps, run };
